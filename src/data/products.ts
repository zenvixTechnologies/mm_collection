/* ---------- Product builder ---------- */

interface Seed {
  name: string;
  categoryId: CategoryId;
  tags?: CategoryId[];
  image: ImageKey;
  /** Focal height for detail crops — tweak per photo so close-ups land on the garment. */
  focus?: [number, number];
  price: number;
  originalPrice: number;
  sizes: Size[];
  colors: ProductColor[];
  stock: number;
  rating: number;
  reviewCount: number;
  featured?: boolean;
  newArrival?: boolean;
  bestSeller?: boolean;
  fabric: string;
  care: string[];
  short: string;
  description: string;
  sold: number;
}

const CATEGORY_CODE: Record<CategoryId, string> = {
  dresses: "DRS",
  tops: "TOP",
  kurtis: "KUR",
  churidhars: "CHU",
  sarees: "SAR",
  "co-ord-sets": "CRD",
  "ethnic-wear": "ETH",
  "western-wear": "WST",
  "casual-wear": "CSL",
  "party-wear": "PTY",
  nightwear: "NGT",
  "feeding-wear": "FDW",
};

function build(seed: Seed, index: number): Product {
  const id = `p${String(index + 1).padStart(3, "0")}`;
  const photo = IMG[seed.image];
  const [upper, lower] = seed.focus ?? [0.38, 0.68];
  return {
    id,
    slug: slugify(seed.name),
    sku: `MM-${CATEGORY_CODE[seed.categoryId]}-${String(1001 + index)}`,
    name: seed.name,
    categoryId: seed.categoryId,
    tags: seed.tags ?? [],
    shortDescription: seed.short,
    description: seed.description,
    originalPrice: seed.originalPrice,
    price: seed.price,
    discount: discountPercent(seed.originalPrice, seed.price),
    images: [portrait(photo), detail(photo, upper, 1.7), detail(photo, lower, 1.5)],
    sizes: seed.sizes,
    colors: seed.colors,
    stock: seed.stock,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    featured: seed.featured ?? false,
    newArrival: seed.newArrival ?? false,
    bestSeller: seed.bestSeller ?? false,
    fabric: seed.fabric,
    care: seed.care,
    // Later entries in the list are treated as more recently added.
    addedAt: index,
    sold: seed.sold,
  };
}

