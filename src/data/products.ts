function audienceOf(categoryId: CategoryId): Audience {
  const category = getCategory(categoryId);
  if (!category) throw new Error(`Unknown category "${categoryId}"`);
  return category.audience;
}

function build(seed: Seed, index: number): Product {
  // Guard the catalogue: a men's product must never be tagged into a women's or kids' category.
  const audience = audienceOf(seed.categoryId);
  for (const tag of seed.tags ?? []) {
    if (audienceOf(tag) !== audience) {
      throw new Error(`"${seed.name}" (${audience}) is tagged with "${tag}" from another audience`);
    }
  }
  const id = `p${String(index + 1).padStart(3, "0")}`;
  const photo = IMG[seed.image];
  const [upper, lower] = seed.focus ?? [0.38, 0.68];
  return {
    id,
    slug: slugify(seed.name),
    sku: `MM-${CATEGORY_CODE[seed.categoryId]}-${String(1001 + index)}`,
    name: seed.name,
    audienceCategory: audience,
    categoryId: seed.categoryId,
    tags: seed.tags ?? [],
    shortDescription: seed.short,
    description: seed.description,
    originalPrice: seed.originalPrice,
    price: seed.price,
    discount: discountPercent(seed.originalPrice, seed.price),
    images: [portrait(photo), detail(photo, upper, 1.7), detail(photo, lower, 1.5)],
    sizes: seed.sizes,
    colors: seed.colors,
    stock: seed.stock,
    rating: seed.rating,
    reviewCount: seed.reviewCount,
    featured: seed.featured ?? false,
    newArrival: seed.newArrival ?? false,
    bestSeller: seed.bestSeller ?? false,
    fabric: seed.fabric,
    care: seed.care,
    // Later entries in the list are treated as more recently added.
    addedAt: index,
    sold: seed.sold,
  };
}

