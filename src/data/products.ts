export const products: Product[] = seeds.map(build);

export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string) {
  return products.find((p) => p.id === id);
}

export function productInCategory(product: Product, categoryId: string) {
  return product.categoryId === categoryId || product.tags.includes(categoryId as never);
}

export function getProductsByCategory(categoryId: string) {
  return products.filter((p) => productInCategory(p, categoryId));
}

export function getProductsByAudience(audience: Audience) {
  return products.filter((p) => p.audienceCategory === audience);
}

/** Optionally limited to one audience — the homepage passes "women". */
export function getNewArrivals(limit?: number, audience?: Audience) {
  const list = products
    .filter((p) => p.newArrival && (!audience || p.audienceCategory === audience))
    .sort((a, b) => b.addedAt - a.addedAt);
  return limit ? list.slice(0, limit) : list;
}

export function getBestSellers(limit?: number, audience?: Audience) {
  const list = products
    .filter((p) => p.bestSeller && (!audience || p.audienceCategory === audience))
    .sort((a, b) => b.sold - a.sold);
  return limit ? list.slice(0, limit) : list;
}

export function getRelatedProducts(product: Product, limit = 4) {
  // Never mix audiences: a men's shirt only suggests other men's products.
  const related = products
    .filter((p) => p.id !== product.id && p.audienceCategory === product.audienceCategory)
    .map((p) => {
      let score = 0;
      if (p.categoryId === product.categoryId) score += 3;
      score += p.tags.filter((t) => t === product.categoryId || product.tags.includes(t)).length;
      return { p, score };
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score || b.p.rating - a.p.rating);
  return related.slice(0, limit).map((x) => x.p);
}

